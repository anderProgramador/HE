-- ============================================================================
-- SAHE - Conceptos
--   Crea DVSAHET16_CONCEPTOS con el modelo de DVSAHET12_TIPOCOMPENSACION.
--
-- Diferencias con el origen BNSAHET16_CONCEPTOS:
--
--   (no existía)        ->  T16_ID
--       Llave sustituta con identidad. El origen se identificaba por concepto
--       + secuencia.
--
--   T16_ESTADOREGISTRO  ->  T16_CACCION
--       Guarda I, U y D, que son acciones y no estados.
--
--   (no existía)        ->  T16_CESTADOREGISTRO
--       'A' mientras la fila es la vigente; 'I' cuando se cierra.
--
--   T16_ESTADOFUNCIONAL se mantiene: es el Activo/Inactivo que ve el usuario.
--
-- El código del concepto es lo que identifica al concepto para el negocio y
-- es lo que referencia T17, así que lleva un único parcial sobre las filas
-- activas: dos conceptos vigentes no pueden compartir código.
-- ============================================================================

