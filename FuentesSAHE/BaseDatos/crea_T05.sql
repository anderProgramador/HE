-- ============================================================================
-- SAHE - Excepción por Puesto
--   Crea DVSAHET05_EXCEPCIONXPUESTO con el mismo modelo que
--   DVSAHET12_TIPOCOMPENSACION: llave sustituta con identidad, vigencia por
--   fechas, acción del movimiento y estado del registro separados.
--
-- Diferencias con el origen BNSAHET05_EXCEPCIONXPUESTO:
--
--   (no existía)  ->  T05_ID
--       Llave sustituta. El origen se identificaba por puesto + secuencia,
--       que obliga a arrastrar dos columnas en cada llamada.
--
--   T05_ESTADOREGISTRO  ->  T05_CACCION
--       La columna anterior guarda I, U y D, que son acciones y no estados.
--
--   (no existía)  ->  T05_CESTADOREGISTRO
--       'A' mientras la fila es la vigente; 'I' cuando se cierra.
--
--   (no existía)  ->  T05_ESTADOFUNCIONAL
--       El Activo/Inactivo que ve el usuario, distinto del estado del
--       registro. En T12 venía del origen; aquí no existía, así que la
--       migración lo deja en 'A' para todas las filas.
--
-- Se ejecuta una sola vez. Volver a correrlo da ORA-00955.
-- ============================================================================

