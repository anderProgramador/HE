-- ============================================================================
-- SAHE - Concepto por Trabajador
--   Crea DVSAHET17_CONCEPTOXTRABAJADOR con el modelo de
--   DVSAHET12_TIPOCOMPENSACION.
--
-- Diferencias con el origen BNSAHET17_CONCEPTOXTRABAJADOR:
--
--   (no existía)        ->  T17_ID
--       Llave sustituta con identidad.
--
--   T16_CCONCEPTO + T16_SECUENCIA  ->  T17_CCONCEPTO
--       El origen apuntaba a UNA VERSIÓN del concepto (código + secuencia).
--       Aquí se guarda solo el código y NO el T16_ID, a propósito: cada vez
--       que se modifica un concepto se inserta una fila nueva con id nuevo,
--       así que una referencia por id quedaría colgando en cada edición. El
--       código, en cambio, identifica al concepto a lo largo de sus versiones,
--       y UNQ_T1601 garantiza que solo haya un concepto vigente por código.
--
--   T17_ESTADOREGISTRO  ->  T17_CACCION
--   (no existía)        ->  T17_CESTADOREGISTRO
--   (no existía)        ->  T17_ESTADOFUNCIONAL
--       Igual que en T05: el concepto de estado funcional no existía en el
--       origen, así que la migración lo deja en 'A'.
--
--   T17_IMPORTEANTERIOR y T17_FCAMBIO se mantienen: son el rastro del último
--       cambio de importe, que el negocio consulta.
-- ============================================================================

